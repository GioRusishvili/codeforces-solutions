#include <bits/stdc++.h>
using namespace std;
int main() {
    string s;
    cin >> s;
    int infinte = 1e9;
    //a-ყველაზე ცოტა რამდენი შესაკრები დაგვჭირდა, თუ ვალი ანუ carry არ გვაქვს
    //b-იგივე, ოღონდ მაშინ როცა შემდეგ თანრიგზე 1 ვალი გადაგვაქვს
    //დასაწყისში ვალი არ გვაქვს, ამიტომ b-ზე ჯერ ვერ მივდივართ
    int a = 0, b = infinte;
    //ბიტებს ვკითხულობთ ბოლოდან, ანუ უმცირესი თანრიგიდან
    for (int i = s.size() - 1; i >= 0; i--) {
        int na, nb; // ახალი a და b
        if (s[i] == '0') {
            //ბიტი 0
            //ვალი რომ არ გვქონდეს, ამ თანრიგში არაფერი გვჭირდება,
            //ამიტომ a უფასოდ რჩება. თუ ვალი გვქონდა, 0 გადაიქცევა 1-ად
            na = min(a, b + 1);
            nb = b + 1;
        } else {
            //ბიტი 1
            //ვალის გარეშე ერთი შესაკრები გვჭირდება. +2^i ვიღებთ და ვალი
            //არ გადადის, ან -2^i ვიღებთ და 1 ვალი გადადის შემდეგზე.
            //თუ ვალიც გვქონდა, 1 + 1 = 2, ამიტომ ამ თანრიგში 0 ჩაიწერება
            //უფასოდ, ვალი კი გადადის შემდეგზე
            na = a + 1;
            nb = min(a + 1, b);
        }
        a = na;
        b = min(nb, infinte);
    }
    //თუ ბოლოს ვალი დაგვრჩა, მის დასაფარად კიდევ ერთი
    //შესაკრები გვჭირდება,ანუ ორი ვარიანტიდან ვირჩევთ უკეთესს
    cout << min(a, b + 1) << endl;
    return 0;
}